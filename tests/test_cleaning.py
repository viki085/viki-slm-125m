# ---------- dispatch / result ----------

def test_unknown_kind_raises():
    with pytest.raises(ValueError):
        cleaning.clean_document("text", "video")


def test_clean_result_reports_sizes():
    r = cleaning.clean_document(GOOD_PY, "code")
    assert r.raw_chars == len(GOOD_PY) and r.clean_chars == len(r.text)


def test_clean_is_deterministic():
    assert cleaning.clean_document(GOOD_SQL, "sql") == cleaning.clean_document(GOOD_SQL, "sql")


def test_sql_parser_internal_errors_do_not_crash(monkeypatch):
    import sqlglot

    def boom(*args, **kwargs):
        raise AttributeError("'NoneType' object has no attribute 'args'")

    monkeypatch.setattr(sqlglot, "parse", boom)
    assert cleaning.clean_document(GOOD_SQL, "sql").reason == "parse_error"


def test_python_keeps_nbconvert_scripts_with_markdown_comments():
    body = "".join(
        f"# In[{i}]:\n\n\n# # Step {i}\n# We explore the data in this cell.\n# More notes about the analysis.\n"
        f"# ## Details {i}\n# Observations are listed below for the reader.\n\n"
        f"values_{i} = [n * {i} for n in range(10)]\nprint(sum(values_{i}))\n\n"
        for i in range(1, 7))
    r = cleaning.clean_document("#!/usr/bin/env python\n# coding: utf-8\n\n" + body, "code")
    assert r.kept, r.reason


def test_sql_ignores_comments_when_checking_parse():
    q = ("# 1. 查询工资最低的员工信息: last_name, salary\n\n#①查询最低的工资\nSELECT MIN(salary)\nFROM employees;\n\n"
         "#②查询last_name,salary\nSELECT last_name, salary\nFROM employees\nWHERE salary = (SELECT MIN(salary) FROM employees);\n"
         "-- 方式一\nSELECT department_id, AVG(salary) AS avg_sal FROM employees GROUP BY department_id;\n")
    r = cleaning.clean_document(q, "sql")
    assert r.kept, r.reason
    assert "查询工资最低" in r.text  # comments are kept in the output
